/* ============================================================================
   SEO — one source of truth for the domain, the shared metadata defaults, and
   the structured data builders.
   ----------------------------------------------------------------------------
   Every schema here is assembled from content that actually exists on the
   page. Nothing describes the business in ways the site does not already
   state: no AggregateRating, no Review, no Offer, no invented address or
   social profiles. Fabricated markup of that kind is a structured-data spam
   violation and gets rich results revoked, which is a worse outcome than not
   having them. `sameAs`, ratings and contact points can be filled in once
   there are real values to point at.
   ========================================================================== */

